/// The standalone flower symbol traced from the Grazi Braz brand PDF.
class GraziSimbolo extends StatelessWidget {
  const GraziSimbolo({
    super.key,
    this.size = 44,
    this.color = const Color(0xFF02594F),
  });

  final double size;
  final Color color;

  @override
  Widget build(BuildContext context) => CustomPaint(
    size: Size.square(size),
    painter: _GraziFlowerPainter(_simboloVector, color),
  );
}

class _GraziFlowerPainter extends CustomPainter {
  const _GraziFlowerPainter(this.path, this.color);

  final Path path;
  final Color color;

  @override
  void paint(Canvas canvas, Size size) {
    final bounds = path.getBounds();
    if (bounds.isEmpty) return;
    final scale = math.min(
      size.width / bounds.width,
      size.height / bounds.height,
    );
    final offsetX = (size.width - bounds.width * scale) / 2;
    final offsetY = (size.height - bounds.height * scale) / 2;

    canvas.save();
    canvas.translate(offsetX, offsetY);
    canvas.scale(scale, -scale);
    canvas.translate(-bounds.left, -bounds.bottom);
    canvas.drawPath(path, Paint()..color = color);
    canvas.restore();
  }

  @override
  bool shouldRepaint(covariant _GraziFlowerPainter oldDelegate) =>
      oldDelegate.path != path || oldDelegate.color != color;
}

